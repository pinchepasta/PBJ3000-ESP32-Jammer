"""Give a multiapp extension its app's own Kconfig values.

An extension compiles against the host's autoconf.h, which lacks the app's
CONFIG_APP_* options (two apps may define one with different defaults). This
takes the options the app's Kconfig defines itself, their defaults and the
app's configuration files, and writes #undef/#define lines the extension
includes after autoconf.h.

Only the Kconfig the apps use: one unconditional default per option, "depends
on" a single symbol, "select" only of host options (which must be set).
"""

import argparse
import re
import sys

CONFIG = re.compile(r"^config\s+(APP_\w+)\s*$")
TYPE = re.compile(r"^\s+(bool|int|hex|string)\b")
DEFAULT = re.compile(r"^\s+default\s+(.+?)\s*$")
DEPENDS = re.compile(r"^\s+depends on\s+(\w+)\s*$")
SELECT = re.compile(r"^\s+select\s+(\w+)\s*$")
ASSIGN = re.compile(r"^CONFIG_(\w+)=(.*)$")


def parse_kconfig(path):
    options = {}
    current = None
    with open(path) as f:
        for line in f:
            if m := CONFIG.match(line):
                current = options[m.group(1)] = {"type": None, "default": None,
                                                 "depends": None, "select": []}
                continue
            if current is None:
                continue
            if re.match(r"^\S", line):
                current = None
            elif m := TYPE.match(line):
                current["type"] = m.group(1)
            elif m := DEFAULT.match(line):
                if " if " in m.group(1):
                    sys.exit(f"{path}: conditional default not supported: {line.strip()}")
                if current["default"] is None:
                    current["default"] = m.group(1)
            elif m := DEPENDS.match(line):
                current["depends"] = m.group(1)
            elif m := SELECT.match(line):
                current["select"].append(m.group(1))
            elif re.match(r"^\s+(depends|select|imply|prompt)\b", line):
                sys.exit(f"{path}: not supported: {line.strip()}")
    return options


def parse_conf(path):
    values = {}
    with open(path) as f:
        for line in f:
            if m := ASSIGN.match(line.strip()):
                values[m.group(1)] = m.group(2)
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--kconfig", required=True, help="the app's Kconfig file")
    parser.add_argument("--host-config", required=True, help="the host's .config")
    parser.add_argument("--conf", action="append", default=[],
                        help="the app's configuration files, in order")
    parser.add_argument("--out", required=True, help="header to write")
    args = parser.parse_args()

    options = parse_kconfig(args.kconfig)
    host = parse_conf(args.host_config)
    values = {name: opt["default"] for name, opt in options.items()}
    for conf in args.conf:
        for name, value in parse_conf(conf).items():
            if name in options:
                values[name] = value

    def enabled(symbol):
        if symbol in options:
            return values[symbol] == "y" and enabled_dep(symbol)
        return host.get(symbol) == "y"

    def enabled_dep(name):
        dep = options[name]["depends"]
        return dep is None or enabled(dep)

    lines = ["/* Generated by apps/multiapp/appconfig.py from " + args.kconfig + ". */", ""]
    for name, opt in options.items():
        value = values[name]
        lines.append(f"#undef CONFIG_{name}")
        if not enabled_dep(name) or value is None or value == "n":
            continue
        if opt["type"] == "bool":
            lines.append(f"#define CONFIG_{name} 1")
            for sel in opt["select"]:
                if host.get(sel) != "y":
                    sys.exit(f"{args.kconfig}: {name} selects {sel}, which the host lacks")
        else:
            lines.append(f"#define CONFIG_{name} {value}")
    with open(args.out, "w") as out:
        out.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
