"""Write the multiapp build id, which an app's file must carry to load.

A hash of what the host and its extensions agree on without the linker
checking it: the configuration, the devicetree, the exports (exports.py), the
headers under the given directories and the compiler.
"""

import argparse
import hashlib
import os
import sys


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--out-h", required=True, help="C header with MULTIAPP_BUILD_ID")
    p.add_argument("--out-bin", required=True, help="the 16 id bytes, for apptrail.py")
    p.add_argument("--compiler", required=True, help="compiler id and version")
    p.add_argument("--file", action="append", default=[], help="a file to hash")
    p.add_argument("--dir", action="append", default=[], help="a header tree to hash")
    a = p.parse_args()

    h = hashlib.sha256()
    h.update(a.compiler.encode())
    for path in a.file:
        h.update(b"\0file\0" + open(path, "rb").read())
    for top in a.dir:
        for root, dirs, files in os.walk(top):
            dirs.sort()
            for name in sorted(f for f in files if f.endswith(".h")):
                path = os.path.join(root, name)
                h.update(b"\0" + os.path.relpath(path, top).encode() + b"\0")
                h.update(open(path, "rb").read())
    digest = h.digest()[:16]

    with open(a.out_bin, "wb") as f:
        f.write(digest)
    with open(a.out_h, "w") as f:
        f.write("/* Generated by apps/multiapp/buildid.py. */\n\n")
        f.write("#define MULTIAPP_BUILD_ID {" + ", ".join(f"0x{b:02x}" for b in digest) + "}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
