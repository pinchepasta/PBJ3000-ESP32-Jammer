#ifndef MULTIAPP_MULTIAPP_H_
#define MULTIAPP_MULTIAPP_H_

#include <stddef.h>
#include <stdint.h>

#include <zephyr/shell/shell.h>

/* Bumped on incompatible changes below; the host refuses other values. */
#define MULTIAPP_ABI 1U

/* USB classes the host registers for an app, besides the CDC-ACM shell and DFU. */
#define MULTIAPP_USB_NCM    (1U << 0)
#define MULTIAPP_USB_VENDOR (1U << 1)
/* The host's own, in boots without an app: the FAT volume as a USB drive. */
#define MULTIAPP_USB_MSC    (1U << 2)

/* What ends an extension file (apptrail.py), checked before llext reads it. */
struct multiapp_trailer {
	uint32_t magic;
	/* The ELF in front of the trailer, and its CRC-32 (crc32_ieee()). */
	uint32_t elf_size;
	uint32_t crc32;
	/* Stack of the thread that runs the app's main(). */
	uint32_t stack_size;
	uint8_t build_id[16];
};

#define MULTIAPP_TRAILER_MAGIC 0x3150414DU /* "MAP1" */

/* Every extension exports one as "multiapp_info" (generated by CMakeLists.txt). */
struct multiapp_info {
	uint32_t abi;
	const char *name;
	/* The app's own main(), as in its standalone build. */
	int (*main)(void);
};

/*
 * An object the host defines for an extension (include/multiapp/ext.h): the
 * extension leaves one in its .multiapp_host section, exports.py reads it and
 * generates the definition, exported under @a name.
 */
struct multiapp_host_object {
	char name[56];
	uint32_t kind;
	uint32_t arg[3];
};

/* A fixed net_buf pool: arg = count, data size, user data size. */
#define MULTIAPP_HOST_POOL 1U
/* Internal RAM in the area (ESP_SDR_HIGH_BUF_DEFINE()): arg = size, alignment. */
#define MULTIAPP_HOST_AREA 2U

/*
 * Make @p root, a root command of the loaded app, reachable from the host's
 * shell. An extension's SHELL_CMD_REGISTER() calls this from a constructor.
 */
void multiapp_shell_register(const struct shell_static_entry *root);

#endif /* MULTIAPP_MULTIAPP_H_ */
